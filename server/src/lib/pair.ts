// Связь ненаправленная, поэтому в таблице хранится единственным способом:
// aId < bId. Благодаря этому (a,b) и (b,a) — одна и та же строка, а дубликаты
// исключены уникальным индексом на уровне БД.
export function normalizePair(x: bigint, y: bigint): [bigint, bigint] {
	return x < y ? [x, y] : [y, x];
}
