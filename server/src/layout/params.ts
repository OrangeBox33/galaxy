// Коэффициенты раскладки. Все собраны в одном месте — их придётся крутить
// на реальных данных (раздел 7).

export const LAYOUT_PARAMS = {
	// Радиус карты в условных единицах: на нём оказывается 95-й процентиль звёзд.
	R_MAX: 1000,

	// Центральность: вес степени и вес собственной центральности.
	// Степень сохраняет главное правило заказчика («больше друзей → ближе
	// к центру»), собственная центральность работает разрешителем ничьих.
	W_DEGREE: 0.7,
	W_EIGEN: 0.3,
	EIGEN_ITERATIONS: 100,

	// Радиальная привязка: тянет узел на его целевую орбиту.
	// Множитель массы — тяжёлые узлы держат орбиту жёстче лёгких.
	K_RAD: 0.08,

	// Кулоновское отталкивание по всем парам. При n ≤ 200 прямой перебор O(n²) —
	// это ~20 000 пар на итерацию, быстрее любого Barnes-Hut.
	K_REP: 900,
	D_MIN: 14,

	// Пружины на рёбрах. Длина зависит от масс концов: иначе соседи хаба
	// слипаются в комок.
	K_SPR: 0.035,
	L0: 55,
	L_MASS: 0.18,

	// Интегрирование: полуявный Эйлер с охлаждением. Деление силы на массу
	// делает тяжёлые узлы инертными, а мелочь — подвижной.
	DT: 1.0,
	DAMPING: 0.88,
	// В ТЗ здесь 0.985. Согласовано с заказчиком: при таком охлаждении шаг
	// становится ничтожным уже к 350-й итерации, и звёзды замирают, не дойдя
	// до равновесия, — с нескомпенсированными силами. Следующий пересчёт
	// доигрывает недоигранное, и небо переезжает на ~4% радиуса из-за одного
	// нового человека. При 0.995 симуляция успевает досидеться до равновесия.
	COOLING: 0.995,
	ALPHA_MIN: 0.005,

	// Полный пересчёт и инкрементальный: разные стартовые температуры.
	FULL_ALPHA: 1,
	FULL_ITERATIONS: 800,
	// В ТЗ 0.25. Снижено вместе с охлаждением: появление одного человека
	// не повод трясти всё небо (сдвиг медианного узла ~1% вместо ~4%).
	INCREMENTAL_ALPHA: 0.1,
	// В ТЗ 200. Это потолок, а не план: прогон заканчивается сам, когда α падает
	// ниже ALPHA_MIN, — при нынешнем охлаждении около 600-й итерации. Потолок
	// в 200 обрывал бы перекладку на полудвижении, и остаток доигрывался бы
	// при следующем пересчёте. Запас нужен и затем, чтобы звёзды могли
	// приспособиться к изменившемуся графу: ветви — распрямиться, соседи —
	// разойтись, как если бы небо строили заново.
	INCREMENTAL_ITERATIONS: 800,

	// Жёсткое разведение пересечений после каждого шага.
	SEPARATION_GAP: 6,

	// Новый узел ставится рядом с пригласившим, а не в случайное место.
	NEW_NODE_OFFSET: 26,

	// Нормировка масштаба по процентилю, а не по максимуму: один улетевший
	// одиночка не должен сжимать всё небо.
	SCALE_PERCENTILE: 0.95,

	// Зерно ГПСЧ. Math.random() не используется нигде.
	SEED: 0x9e3779b9,
} as const;

// Видимый радиус звезды (раздел 8.2) в мировых единицах. Раскладка использует
// его для жёсткого разведения: звёзды не должны налезать друг на друга.
export function starRadius(degree: number): number {
	return Math.min(Math.max(1.8 + 2.2 * Math.sqrt(degree), 1.8), 14);
}
